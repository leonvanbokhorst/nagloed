#!/usr/bin/env python3
"""Embed presets/*.json into a C++ translation unit.

The plugin's preset browser and the DAW program list are generated from the JSON
files so that the sound-design workstream can add presets without touching C++.
Validation is intentionally light: unknown parameter ids are skipped at runtime
with a debug message, and a dedicated C++ test asserts every id resolves.
"""
import json
import pathlib
import sys


def c_string(value: str) -> str:
    return json.dumps(value)


def main() -> int:
    if len(sys.argv) != 3:
        print("usage: gen_presets.py <preset_dir> <out_dir>", file=sys.stderr)
        return 2
    preset_dir = pathlib.Path(sys.argv[1])
    out_dir = pathlib.Path(sys.argv[2])
    out_dir.mkdir(parents=True, exist_ok=True)

    presets = []
    for path in sorted(preset_dir.glob("*.json")):
        try:
            data = json.loads(path.read_text(encoding="utf-8"))
        except json.JSONDecodeError as exc:
            print(f"invalid JSON in {path}: {exc}", file=sys.stderr)
            return 1
        name = str(data.get("name") or path.stem)
        category = str(data.get("category") or "Factory")
        description = str(data.get("description") or "")
        params = data.get("params") or {}
        if not isinstance(params, dict):
            print(f"params must be an object in {path}", file=sys.stderr)
            return 1
        presets.append((name, category, description, params))

    header = out_dir / "PresetsData.h"
    header.write_text("""#pragma once
// generated by scripts/gen_presets.py — do not edit
namespace nagloed::generated
{
struct PresetData
{
    const char* name;
    const char* category;
    const char* description;
    const char* json;
};
int count();
const PresetData* data();
} // namespace nagloed::generated
""", encoding="utf-8")

    lines = ["// generated by scripts/gen_presets.py — do not edit",
             '#include "PresetsData.h"', "", "namespace nagloed::generated", "{"]
    lines.append("static const PresetData kPresets[] = {")
    for name, category, description, params in presets:
        payload = json.dumps({"name": name, "category": category,
                              "description": description, "params": params},
                             ensure_ascii=False, separators=(",", ":"))
        lines.append("    { %s, %s, %s, R\"NAGLOEDJSON(%s)NAGLOEDJSON\" },"
                     % (c_string(name), c_string(category), c_string(description), payload))
    if not presets:
        lines.append('    { "", "", "", "" },  // placeholder, never read: presets::count() adds Init')
    lines.append("};")
    lines.append("int count() { return (int) (sizeof (kPresets) / sizeof (kPresets[0])); }")
    lines.append("const PresetData* data() { return kPresets; }")
    lines.append("} // namespace nagloed::generated")
    (out_dir / "PresetsData.cpp").write_text("\n".join(lines) + "\n", encoding="utf-8")

    print(f"embedded {len(presets)} preset(s)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
